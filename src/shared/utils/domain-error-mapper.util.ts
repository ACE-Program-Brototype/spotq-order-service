	[CART_ERROR_CODES.CART_ITEM_NOT_FOUND]: HttpStatus.NOT_FOUND,
	[CART_ERROR_CODES.MENU_ITEM_NOT_FOUND]: HttpStatus.NOT_FOUND,
	[CART_ERROR_CODES.CART_EXPIRED]: HttpStatus.GONE,
	[CART_ERROR_CODES.FORBIDDEN_CART_ACCESS]: HttpStatus.FORBIDDEN,
